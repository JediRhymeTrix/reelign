"""Pure generation of native GitHub Actions schedule-profile wrappers.

The reusable worker owns shared state concurrency. Rendering has no artificial
profile cap; installations must consider GitHub Actions workflow/schedule limits.
"""

from .config import Settings


def render_workflows(settings: Settings) -> dict[str, str]:
    """Return deterministic relative filenames and YAML; never touch the filesystem.

    Native timezone handling retains daylight-saving behavior. Manual-only
    profiles deliberately have no wrapper. Profile names, cron syntax and IANA
    timezone identifiers have been validated before insertion into YAML.
    """
    workflows = {}
    for profile, schedule in sorted(settings.schedules.items()):
        if schedule.cron is None:
            continue
        workflows[f"schedule-{profile}.yml"] = (
            "# Generated by python manage.py render-workflows; do not edit.\n"
            f"name: Reelign schedule ({profile})\n"
            "\n"
            "on:\n"
            "  schedule:\n"
            f"    - cron: '{schedule.cron}'\n"
            f"      timezone: '{schedule.timezone}'\n"
            "\n"
            "jobs:\n"
            "  sync:\n"
            "    if: ${{ vars.REELIGN_ENABLED == 'true' && github.ref == "
            "format('refs/heads/{0}', github.event.repository.default_branch) }}\n"
            "    permissions:\n"
            "      contents: write\n"
            "    uses: ./.github/workflows/reusable-sync.yml\n"
            "    with:\n"
            f"      profile: '{profile}'\n"
            "    secrets: inherit\n"
        )
    return workflows