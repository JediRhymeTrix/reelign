from pathlib import Path
import sys
import unittest
from unittest.mock import patch
from zoneinfo import ZoneInfoNotFoundError

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from syncer.config import Schedule, Settings
from syncer.model import SyncError
from syncer.scheduling import render_workflows


class ScheduleValidationTests(unittest.TestCase):
    def test_valid_five_field_cron_ranges_lists_steps_and_names(self):
        expressions = (
            "17 * * * *", "*/5 * * * *", "0,15,30,45 1-23/2 * * *",
            "5-55/10 2 * JAN,MAR MON-FRI", "0 0 1 */2 *",
            "7/20 0,12 * jan-dec/2 sun", "0 3 * * 0-6",
            "0,5,10,15,20,25,30,35,40,45,50,55 * * * *",
        )
        for expression in expressions:
            with self.subTest(expression=expression):
                self.assertEqual(Schedule(expression).cron, expression)

    def test_invalid_field_count_syntax_bounds_and_nonstandard_macros(self):
        expressions = (
            "", "@hourly", "0 17 * * * *", "17 * * *", "17 * * * * * *",
            "60 * * * *", "0 24 * * *", "0 0 0 * *", "0 0 32 * *",
            "0 0 * 0 *", "0 0 * 13 *", "0 0 * * 8", "0 0 * * -1",
            "0 0 * BAD *", "0 0 * * FUNDAY", "0 0 * * MONDAY",
            "0 0 ? * *", "0 0 L * *", "0 0 * * MON#2", "0 0 * * 5L",
            "*/0 * * * *", "0 */0 * * *", "0-30/-5 * * * *",
            "0-60/5 * * * *", "55-5/5 * * * *", "0,,5 * * * *",
            "0 0 * * MON-SUN", "0 0 * * MON/0", "0 0 * * 1/2/3",
            "0 0 * * *\nname: injected", "0 0 * * *\r", "0 0 * * *'",
        )
        for expression in expressions:
            with self.subTest(expression=expression), self.assertRaises(SyncError):
                Schedule(expression)
        for value in (True, 17, [], {}):
            with self.subTest(value=value), self.assertRaises(SyncError):
                Schedule(value)

    def test_minimum_five_minute_granularity_including_hour_boundary(self):
        for expression in ("* * * * *", "*/1 * * * *", "*/2 * * * *",
                           "*/3 * * * *", "*/4 * * * *", "0,4 * * * *",
                           "0,59 * * * *", "1,58 * * * *", "*/7 * * * *"):
            with self.subTest(expression=expression), self.assertRaises(SyncError):
                Schedule(expression)
        for expression in ("*/5 * * * *", "0,5 * * * *", "1,56 * * * *"):
            with self.subTest(expression=expression):
                self.assertEqual(Schedule(expression).cron, expression)

    def test_manual_and_none_mean_no_scheduled_workflow(self):
        self.assertIsNone(Schedule("manual").cron)
        self.assertIsNone(Schedule(None).cron)
        for value in ("MANUAL", "manual * * * *"):
            with self.subTest(value=value), self.assertRaises(SyncError):
                Schedule(value)

    def test_timezone_validation_and_utc_builtin_fallback(self):
        self.assertEqual(Schedule(timezone="UTC").timezone, "UTC")
        for value in ("", "Not/A_Zone", "../UTC", "/UTC", "UTC\n", True, None):
            with self.subTest(value=value), self.assertRaises(SyncError):
                Schedule(timezone=value)
        with patch("syncer.config.ZoneInfo", side_effect=ZoneInfoNotFoundError):
            self.assertEqual(Schedule(timezone="UTC").timezone, "UTC")
            with self.assertRaises(SyncError):
                Schedule(timezone="Europe/London")


class RenderWorkflowTests(unittest.TestCase):
    def test_default_workflow_exact_native_schedule_and_safe_reusable_job(self):
        expected = """# Generated by python manage.py render-workflows; do not edit.
name: Reelign schedule (default)

on:
  schedule:
    - cron: '17 * * * *'
      timezone: 'UTC'

jobs:
  sync:
    if: ${{ vars.REELIGN_ENABLED == 'true' && github.ref == format('refs/heads/{0}', github.event.repository.default_branch) }}
    permissions:
      contents: write
    uses: ./.github/workflows/reusable-sync.yml
    with:
      profile: 'default'
    secrets: inherit
"""
        self.assertEqual(render_workflows(Settings()), {"schedule-default.yml": expected})

    def test_manual_profiles_skipped_and_render_order_deterministic(self):
        schedules = {"nightly": Schedule("30 2 * * *"), "default": Schedule("manual"),
                     "frequent": Schedule("*/15 * * * *")}
        settings = Settings(schedules=schedules)
        first = render_workflows(settings)
        second = render_workflows(Settings(schedules=dict(reversed(list(schedules.items())))))
        self.assertEqual(first, second)
        self.assertEqual(list(first), ["schedule-frequent.yml", "schedule-nightly.yml"])
        self.assertEqual(render_workflows(Settings(schedules={"default": Schedule(None)})), {})
        self.assertEqual(settings.schedules, schedules)

    def test_renderer_has_no_artificial_profile_cap_or_filesystem_writes(self):
        settings = Settings(schedules={f"profile-{number}": Schedule()
                                       for number in range(110)})
        with patch.object(Path, "write_text", side_effect=AssertionError("not pure")):
            workflows = render_workflows(settings)
        self.assertEqual(len(workflows), 110)
        for filename, text in workflows.items():
            self.assertEqual(Path(filename).name, filename)
            self.assertTrue(filename.startswith("schedule-profile-"))
            self.assertNotIn("concurrency:", text)
            self.assertNotIn("C:\\", text)

    def test_native_timezone_is_preserved_not_converted_to_fixed_utc(self):
        with patch("syncer.config.ZoneInfo"):
            settings = Settings(schedules={"local": Schedule("30 2 * * *", "Europe/London")})
        text = render_workflows(settings)["schedule-local.yml"]
        self.assertIn("cron: '30 2 * * *'", text)
        self.assertIn("timezone: 'Europe/London'", text)
        self.assertIn("profile: 'local'", text)


